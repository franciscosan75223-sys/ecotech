-- EcoTech: ejecutar TODO en SQL Editor del proyecto nuevo de Supabase.
-- Conserva las seis tablas del equipo; no importa datos desde MySQL.
-- Puede repetirse en este mismo esquema. No elimina tablas ni registros.
BEGIN;

-- Un esquema es una carpeta lógica para las tablas de nuestro programa.
-- El programa Python se conecta a PostgreSQL directamente mediante SSL.
CREATE SCHEMA IF NOT EXISTS ecotech;
REVOKE ALL ON SCHEMA ecotech FROM PUBLIC, anon, authenticated;

CREATE TABLE IF NOT EXISTS ecotech.empleado (
    id_empleado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    direccion VARCHAR(200) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    correo VARCHAR(150) NOT NULL,
    fecha_inicio DATE NOT NULL,
    salario NUMERIC(12, 2) NOT NULL,
    rol VARCHAR(50) NOT NULL DEFAULT 'Empleado',
    CONSTRAINT ck_empleado_salario CHECK (salario >= 0),
    CONSTRAINT ck_empleado_nombre CHECK (CHAR_LENGTH(TRIM(nombre)) > 0),
    CONSTRAINT ck_empleado_rol CHECK (rol IN ('Empleado', 'Gerente'))
);

CREATE TABLE IF NOT EXISTS ecotech.cuenta_usuario (
    id_cuenta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado INTEGER NOT NULL UNIQUE,
    nombre_usuario VARCHAR(50) COLLATE "C" NOT NULL UNIQUE,
    correo VARCHAR(150) NOT NULL,
    -- BYTEA es el equivalente de los bytes cifrados que guardaba MySQL.
    contrasena_cifrada BYTEA NOT NULL,
    CONSTRAINT ck_cuenta_cifrado CHECK (OCTET_LENGTH(contrasena_cifrada) <= 2048),
    CONSTRAINT fk_cuenta_empleado FOREIGN KEY (id_empleado)
        REFERENCES ecotech.empleado(id_empleado) ON DELETE CASCADE
);

-- Sin claves foráneas: se conserva la evidencia de registros eliminados.
CREATE TABLE IF NOT EXISTS ecotech.historial_cambios (
    id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    operacion VARCHAR(20) NOT NULL CHECK (operacion IN ('AGREGAR', 'ACTUALIZAR', 'ELIMINAR')),
    entidad VARCHAR(30) NOT NULL CHECK (entidad IN ('EMPLEADO', 'CUENTA_USUARIO', 'PROYECTO', 'DEPARTAMENTO', 'ASIGNACION')),
    id_registro INTEGER,
    id_empleado INTEGER,
    -- Conservamos el nombre original para no cambiar el historial del equipo.
    -- Ahora guarda CURRENT_USER de PostgreSQL, no un usuario de MySQL.
    usuario_mysql VARCHAR(288) NOT NULL,
    detalle VARCHAR(500) NOT NULL,
    datos_anteriores TEXT,
    datos_nuevos TEXT
);

CREATE TABLE IF NOT EXISTS ecotech.proyecto (
    id_proyecto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion_proyecto VARCHAR(255) NOT NULL,
    fecha_de_inicio DATE NOT NULL,
    miembro VARCHAR(100) NOT NULL,
    presupuesto NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_proyecto_presupuesto CHECK (presupuesto >= 0),
    CONSTRAINT ck_proyecto_nombre CHECK (CHAR_LENGTH(TRIM(nombre)) > 0)
);

CREATE TABLE IF NOT EXISTS ecotech.departamento (
    id_departamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    departamento VARCHAR(100) NOT NULL,
    gerente_id INTEGER NOT NULL,
    CONSTRAINT fk_departamento_gerente FOREIGN KEY (gerente_id)
        REFERENCES ecotech.empleado(id_empleado) ON DELETE RESTRICT,
    CONSTRAINT ck_departamento_nombre CHECK (CHAR_LENGTH(TRIM(nombre)) > 0)
);

CREATE TABLE IF NOT EXISTS ecotech.asignacion (
    id_asignacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    horas_trabajadas INTEGER NOT NULL,
    tareas_realizadas VARCHAR(255) NOT NULL,
    -- Se admite NULL por compatibilidad con el avance del equipo.
    -- Python exige ambos IDs para guardar nuevos registros.
    id_empleado INTEGER,
    id_proyecto INTEGER,
    CONSTRAINT ck_asignacion_horas CHECK (horas_trabajadas >= 0),
    CONSTRAINT fk_asignacion_empleado FOREIGN KEY (id_empleado)
        REFERENCES ecotech.empleado(id_empleado) ON DELETE RESTRICT,
    CONSTRAINT fk_asignacion_proyecto FOREIGN KEY (id_proyecto)
        REFERENCES ecotech.proyecto(id_proyecto) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_departamento_gerente ON ecotech.departamento(gerente_id);
CREATE INDEX IF NOT EXISTS idx_asignacion_empleado ON ecotech.asignacion(id_empleado);
CREATE INDEX IF NOT EXISTS idx_asignacion_proyecto ON ecotech.asignacion(id_proyecto);
CREATE INDEX IF NOT EXISTS idx_historial_empleado_fecha ON ecotech.historial_cambios(id_empleado, fecha);
CREATE INDEX IF NOT EXISTS idx_historial_fecha ON ecotech.historial_cambios(fecha);
CREATE INDEX IF NOT EXISTS idx_historial_entidad_id_fecha ON ecotech.historial_cambios(entidad, id_registro, fecha);

-- Protección adicional: no se habilita acceso anónimo a datos de empleados.
-- El usuario PostgreSQL del programa administrativo mantiene su acceso.
ALTER TABLE ecotech.empleado ENABLE ROW LEVEL SECURITY;
ALTER TABLE ecotech.cuenta_usuario ENABLE ROW LEVEL SECURITY;
ALTER TABLE ecotech.historial_cambios ENABLE ROW LEVEL SECURITY;
ALTER TABLE ecotech.proyecto ENABLE ROW LEVEL SECURITY;
ALTER TABLE ecotech.departamento ENABLE ROW LEVEL SECURITY;
ALTER TABLE ecotech.asignacion ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA ecotech FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA ecotech FROM PUBLIC, anon, authenticated;

-- Si se activó RLS automático al crear el proyecto, su función solo debe
-- usarse como disparador administrativo, no llamarse desde la API pública.
DO $$
BEGIN
    IF to_regprocedure('public.rls_auto_enable()') IS NOT NULL THEN
        REVOKE EXECUTE ON FUNCTION public.rls_auto_enable() FROM PUBLIC, anon, authenticated;
    END IF;
END $$;
COMMIT;

-- Deben aparecer las seis tablas con seguridad activada.
SELECT tablename AS tabla, rowsecurity AS seguridad_activa
FROM pg_tables WHERE schemaname = 'ecotech' ORDER BY tablename;
